#!/usr/bin/env python3
"""Generates lemon.obj: an original lemon model (body, stem and leaf) for
example 36. Run from this directory: python3 make_lemon.py"""
import math

def body(phi, theta):
    # Length along x with pointed ends, a slightly flattened round section.
    tip = 0.16 * (math.exp(-(phi / 0.28) ** 2) + math.exp(-((math.pi - phi) / 0.28) ** 2))
    x = math.cos(phi) * (1.0 + tip)
    r = 0.72 * math.sin(phi) ** 0.85 * (1.0 + 0.012 * math.sin(7 * theta) * math.sin(5 * phi))
    return (x, r * math.cos(theta), r * math.sin(theta) * 0.95)

def sub(a, b): return tuple(p - q for p, q in zip(a, b))
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
def norm(a):
    l = math.sqrt(sum(c * c for c in a)) or 1.0
    return tuple(c / l for c in a)

out = ["# An original lemon for Citronnade's example 36 (generated by make_lemon.py)"]
v, vn, vt = [], [], []
def vertex(p, n, uv):
    v.append(p); vn.append(n); vt.append(uv)
    return len(v)

# Body: rows along phi (0..pi), columns around theta; the poles get their
# own vertices so normals stay smooth.
ROWS, COLS = 26, 36
grid = []
for i in range(ROWS + 1):
    phi = 1e-3 + (math.pi - 2e-3) * i / ROWS
    row = []
    for j in range(COLS + 1):
        theta = 2 * math.pi * j / COLS
        p = body(phi, theta)
        e = 1e-3
        dphi = sub(body(phi + e, theta), body(phi - e, theta))
        dtheta = sub(body(phi, theta + e), body(phi, theta - e))
        n = norm(cross(dphi, dtheta))
        if sum(a * b for a, b in zip(n, p)) < 0:
            n = tuple(-c for c in n)
        row.append(vertex(p, n, (j / COLS, i / ROWS)))
    grid.append(row)
faces = {"body": [], "stem": [], "leaf": []}
for i in range(ROWS):
    for j in range(COLS):
        a, b, c, d = grid[i][j], grid[i][j + 1], grid[i + 1][j + 1], grid[i + 1][j]
        faces["body"].append((a, d, c, b))

# Stem: a short cylinder at the +x tip.
SEG = 10
base_x, top_x, rad = 1.12, 1.3, 0.04
ring = []
for k in range(SEG + 1):
    a = 2 * math.pi * k / SEG
    n = (0.0, math.cos(a), math.sin(a))
    lo = vertex((base_x, rad * math.cos(a), rad * math.sin(a)), n, (k / SEG, 0))
    hi = vertex((top_x, rad * 0.8 * math.cos(a), rad * 0.8 * math.sin(a)), n, (k / SEG, 1))
    ring.append((lo, hi))
for k in range(SEG):
    (l0, h0), (l1, h1) = ring[k], ring[k + 1]
    faces["stem"].append((l0, h0, h1, l1))

# Leaf: a pointed ellipse bent upwards, both sides.
L, W = 10, 4
for side in (1, -1):
    pts = []
    for i in range(L + 1):
        t = i / L
        half = 0.22 * math.sin(math.pi * t) ** 0.8
        row = []
        for j in range(W + 1):
            s = -1 + 2 * j / W
            x = top_x - 0.05 + 0.65 * t
            y = 0.06 + 0.25 * t * t + 0.05 * (1 - s * s) * math.sin(math.pi * t)
            z = s * half
            row.append((x, y, z))
        pts.append(row)
    idx = []
    for i in range(L + 1):
        r = []
        for j in range(W + 1):
            i0, i1 = max(i - 1, 0), min(i + 1, L)
            j0, j1 = max(j - 1, 0), min(j + 1, W)
            n = norm(cross(sub(pts[i1][j], pts[i0][j]), sub(pts[i][j1], pts[i][j0])))
            if n[1] * side < 0:
                n = tuple(-c for c in n)
            r.append(vertex(pts[i][j], n, (j / W, i / L)))
        idx.append(r)
    for i in range(L):
        for j in range(W):
            a, b, c, d = idx[i][j], idx[i][j + 1], idx[i + 1][j + 1], idx[i + 1][j]
            faces["leaf"].append((a, b, c, d) if side < 0 else (a, d, c, b))

for p in v: out.append("v %.5f %.5f %.5f" % p)
for t in vt: out.append("vt %.4f %.4f" % t)
for n in vn: out.append("vn %.5f %.5f %.5f" % n)
for name, fs in faces.items():
    out.append("o " + name)
    for f in fs:
        out.append("f " + " ".join("%d/%d/%d" % (i, i, i) for i in f))
open("lemon.obj", "w").write("\n".join(out) + "\n")
print(len(v), "vertices,", sum(len(f) for f in faces.values()), "quads")
